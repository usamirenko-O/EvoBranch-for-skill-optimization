"""Run the native SkillOpt trainer on shared benchmark splits."""
from __future__ import annotations

import hashlib
import json
import os
import subprocess
import sys
import time
from pathlib import Path

from integration.common.paths import SKILLOPT_ROOT, WORKSPACE_ROOT
from integration.experiment.cost import PhaseCostAccumulator
from integration.experiment.runners.base import OptimizationResult, OptimizerRunner, RunContext
from integration.experiment.runners.skills import NATIVE_START_CONDITION
from integration.experiment.runners.split_materialization import (
    materialize_skillopt_split,
    skillopt_env_overrides,
)

CONFIG_OVERRIDE_DIR = WORKSPACE_ROOT / "integration" / "experiment" / "skillopt_configs"

#: Shared-harness option -> SkillOpt env config key, per benchmark.
#:
#: The benchmark / solver contract (`main_experiment/baseline_hparams.json`
#: `harness.<benchmark>`) is a property of the benchmark, not of a method: the
#: three papers all fix the execution budget per benchmark and vary only the
#: adaptation procedure. SkillOpt's optimization phase runs in SkillOpt's OWN
#: env rather than the shared Direct harness, so the contract has to be handed
#: to that env explicitly, or SkillOpt would collect evidence and gate
#: candidates under a different budget (its yaml defaults: 24 tool turns, 30
#: repair turns) than the one every cell is validated and deployed under.
HARNESS_TO_SKILLOPT_ENV = {
    "officeqa": {"max_tool_turns": "env.max_tool_turns"},
    "spreadsheetbench": {"max_turns": "env.max_turns", "exec_timeout": "env.exec_timeout"},
    "alfworld": {"max_steps": "env.max_steps"},
    "livemathematicianbench": {},
    "livecodebench": {},
    "pubmedqa": {},
    "chemllmbench": {},
}

#: The execution-budget options the shared Direct harness honours, per
#: benchmark (`integration/harness/registry.py::build_harness`). Anything
#: else in `harness_options` is ignored by the shared harness too (resource
#: locations such as `alfworld_data` / `docs_root`, or an option meant for
#: another benchmark), so it is not a budget and creates no asymmetry.
SHARED_HARNESS_BUDGET_OPTIONS = {
    "officeqa": ("max_tool_turns",),
    "spreadsheetbench": ("max_turns", "exec_timeout"),
    "alfworld": ("max_steps", "history_length"),
    "livemathematicianbench": (),
    "livecodebench": (),
    "pubmedqa": (),
    "chemllmbench": (),
}


def harness_cfg_options(benchmark: str, harness_options: dict) -> list:
    """The `--cfg-options` that make SkillOpt's own env honour the run's
    harness contract. A budget the shared harness honours but SkillOpt's env
    cannot is an error, not a silent asymmetry."""
    mapping = HARNESS_TO_SKILLOPT_ENV[benchmark]
    budgets = SHARED_HARNESS_BUDGET_OPTIONS[benchmark]
    out: list = []
    for key, value in (harness_options or {}).items():
        if key in mapping:
            out.append(f"{mapping[key]}={value}")
        elif key in budgets:
            raise ValueError(
                f"harness option {key!r} bounds the shared harness for {benchmark!r} but has "
                "no SkillOpt env counterpart; SkillOpt's optimization-phase rollouts would run "
                f"under a different budget than validation and deployment. Mappable: {sorted(mapping)}"
            )
    return out

#: benchmark -> (SkillOpt config name, default initial-skill path)
_BENCHMARK_CONFIG = {
    "officeqa": ("officeqa", "skillopt/envs/officeqa/skills/initial.md"),
    "spreadsheetbench": ("spreadsheetbench", "skillopt/envs/spreadsheetbench/skills/initial.md"),
    "alfworld": ("alfworld", "skillopt/envs/alfworld/skills/initial.md"),
    "livemathematicianbench": (
        "livemathematicianbench",
        "skillopt/envs/livemathematicianbench/skills/initial.md",
    ),
    "livecodebench": ("livecodebench", "skillopt/envs/livecodebench/skills/initial.md"),
    "pubmedqa": ("pubmedqa", "skillopt/envs/pubmedqa/skills/initial.md"),
    "chemllmbench": ("chemllmbench", "skillopt/envs/chemllmbench/skills/initial.md"),
}


def config_override_path(benchmark: str) -> Path:
    """The external config that inherits SkillOpt's own benchmark config.

    Lives outside `SkillOpt/` (nothing in that repo is edited) and only sets
    `model.backend: openai_compatible`, which is the one value that cannot be
    passed on the command line -- `scripts/train.py`'s `--backend` choice list
    does not include it.
    """
    name, _ = _BENCHMARK_CONFIG[benchmark]
    return CONFIG_OVERRIDE_DIR / f"{name}.override.yaml"


def _write_config_overrides() -> None:
    CONFIG_OVERRIDE_DIR.mkdir(parents=True, exist_ok=True)
    for benchmark, (name, _) in _BENCHMARK_CONFIG.items():
        path = CONFIG_OVERRIDE_DIR / f"{name}.override.yaml"
        if path.exists():
            continue
        path.write_text(
            "# Generated by integration/experiment/runners/skillopt.py.\n"
            "# Inherits SkillOpt's own benchmark config and changes exactly one\n"
            "# thing: route both LLM roles through the generic OpenAI-compatible\n"
            "# backend, which cannot be selected from scripts/train.py's CLI.\n"
            "# Connection details come from environment variables at launch;\n"
            "# nothing account-specific is written here.\n"
            f"_base_: ../../../SkillOpt/configs/{name}/default.yaml\n"
            "\n"
            "model:\n"
            "  backend: openai_compatible\n",
            encoding="utf-8",
        )


def _cost_from_summary(summary: dict, accumulator: PhaseCostAccumulator) -> str:
    """Fold SkillOpt's own optimization token totals into the phase.

    SkillOpt only splits its token timeline into `optimization_token_summary`
    / `deployment_token_summary` when its own held-out evaluation runs. This
    runner turns that off (`evaluation.eval_test=false`) precisely so that
    deployment is the shared harness's job -- which means the run's grand
    total `token_summary._total` *is* the optimization cost, with nothing else
    in it. Preferring the split bucket when present keeps this correct either
    way; the key actually used is recorded in the artifact.
    """
    split_bucket = (summary.get("optimization_token_summary") or {}).get("_total")
    if split_bucket:
        source_key = "optimization_token_summary._total"
        bucket = split_bucket
    else:
        source_key = "token_summary._total (eval_test disabled: the whole run is optimization)"
        bucket = (summary.get("token_summary") or {}).get("_total") or {}
    accumulator.adopt_native_totals(
        llm_calls=int(bucket.get("calls", 0) or 0),
        input_tokens=bucket.get("prompt_tokens"),
        output_tokens=bucket.get("completion_tokens"),
        cached_tokens=bucket.get("cached_tokens"),
        role="skillopt_native_tracker",
    )
    return source_key


class SkillOptRunner(OptimizerRunner):
    optimizer = "skillopt"

    @staticmethod
    def preflight(ctx: RunContext) -> list:
        errors = []
        benchmark = ctx.adapter.name
        if benchmark not in _BENCHMARK_CONFIG:
            errors.append(f"SkillOpt has no native env for benchmark {benchmark!r}")
            return errors
        _, skill_rel = _BENCHMARK_CONFIG[benchmark]
        if not (SKILLOPT_ROOT / skill_rel).is_file():
            errors.append(f"missing SkillOpt initial skill: {SKILLOPT_ROOT / skill_rel}")
        if not (SKILLOPT_ROOT / "scripts" / "train.py").is_file():
            errors.append("missing SkillOpt/scripts/train.py")
        if not ctx.train_ids:
            errors.append("manifest train split is empty; SkillOpt cannot optimize")
        try:
            harness_cfg_options(benchmark, ctx.harness_options)
        except ValueError as exc:
            errors.append(str(exc))
        return errors

    def optimize(self, ctx: RunContext) -> OptimizationResult:
        benchmark = ctx.adapter.name
        _, skill_rel = _BENCHMARK_CONFIG[benchmark]
        _write_config_overrides()

        split_dir = materialize_skillopt_split(ctx.manifest, ctx.workdir("skillopt_split"))
        out_root = ctx.workdir("skillopt_out")
        skill_init = SKILLOPT_ROOT / skill_rel

        cfg = ctx.config
        env = os.environ.copy()
        for role, alias, max_tokens in (
            ("TARGET", cfg.solver_model, cfg.max_tokens),
            ("OPTIMIZER", cfg.optimizer_model, cfg.optimizer_max_tokens),
        ):
            env[f"{role}_OPENAI_COMPATIBLE_BASE_URL"] = cfg.proxy_base_url
            env[f"{role}_OPENAI_COMPATIBLE_MODEL"] = alias
            env[f"{role}_OPENAI_COMPATIBLE_MAX_TOKENS"] = str(max_tokens)
            env[f"{role}_OPENAI_COMPATIBLE_API_KEY"] = cfg.api_key
        if benchmark == "alfworld":
            env["ALFWORLD_DATA"] = ctx.harness_options.get("alfworld_data") or env.get(
                "ALFWORLD_DATA", ""
            )
        if benchmark == "spreadsheetbench":


            for role in ("TARGET", "OPTIMIZER"):
                env[f"{role}_AZURE_OPENAI_AUTH_MODE"] = "openai_compatible"
                env[f"{role}_AZURE_OPENAI_ENDPOINT"] = cfg.proxy_base_url
                env[f"{role}_AZURE_OPENAI_API_KEY"] = cfg.api_key
            env["AZURE_OPENAI_AUTH_MODE"] = "openai_compatible"
            env["AZURE_OPENAI_ENDPOINT"] = cfg.proxy_base_url
            env["AZURE_OPENAI_API_KEY"] = cfg.api_key

        batch_size = min(int(cfg.extra.get("skillopt_batch_size", len(ctx.train_ids))), len(ctx.train_ids))
        cfg_options = [
            f"env.split_dir={split_dir.resolve()}",
            f"env.skill_init={skill_init.resolve()}",
            "env.split_mode=split_dir",
            f"model.target={cfg.solver_model}",
            f"model.optimizer={cfg.optimizer_model}",
            # SkillOpt cross-checks train_size against the loaded split and
            # aborts on a mismatch; its per-benchmark configs pin the size of
            # the split they shipped with, which a user manifest replaces.
            f"train.train_size={len(ctx.train_ids)}",
            f"train.batch_size={batch_size}",
            f"train.num_epochs={int(cfg.extra.get('skillopt_num_epochs', 1))}",
            # Deployment is the shared harness's job, not SkillOpt's.
            "evaluation.eval_test=false",
        ]
        for key, value in skillopt_env_overrides(benchmark).items():
            cfg_options.append(f"{key}={value}")
        # The benchmark / solver contract, applied to SkillOpt's own env so its
        # optimization-phase rollouts run under the same budget as validation
        # and deployment (see HARNESS_TO_SKILLOPT_ENV).
        harness_contract = harness_cfg_options(benchmark, ctx.harness_options)
        cfg_options.extend(harness_contract)
        cfg_options.extend(cfg.extra.get("skillopt_cfg_options", []))

        argv = [
            sys.executable,
            str(SKILLOPT_ROOT / "scripts" / "train.py"),
            "--config",
            str(config_override_path(benchmark)),
            "--cfg-options",
            *cfg_options,
            "--out_root",
            str(out_root.resolve()),
        ]
        (ctx.run_dir / "skillopt_launch.json").write_text(
            json.dumps(
                {
                    "argv": argv,
                    "cfg_options": cfg_options,
                    "env_redacted": {
                        k: ("***" if "API_KEY" in k else v)
                        for k, v in env.items()
                        if k.startswith(("TARGET_", "OPTIMIZER_", "ALFWORLD_", "AZURE_OPENAI_"))
                    },
                },
                indent=2,
            ),
            encoding="utf-8",
        )

        t0 = time.time()
        proc = subprocess.run(
            argv,
            cwd=WORKSPACE_ROOT,
            env=env,
            capture_output=True,
            text=True,
            timeout=ctx.config.extra.get("skillopt_timeout_s") or None,
        )
        wall = time.time() - t0
        (ctx.run_dir / "skillopt_stdout.log").write_text(proc.stdout[-500_000:], encoding="utf-8")
        (ctx.run_dir / "skillopt_stderr.log").write_text(proc.stderr[-500_000:], encoding="utf-8")
        if proc.returncode != 0:
            raise RuntimeError(
                f"SkillOpt/scripts/train.py exited {proc.returncode}; "
                f"see {ctx.run_dir / 'skillopt_stderr.log'}\n"
                + proc.stderr[-4000:]
            )

        summary_path = out_root / "summary.json"
        summary = json.loads(summary_path.read_text(encoding="utf-8")) if summary_path.exists() else {}

        accumulator = PhaseCostAccumulator("optimization")
        cost_source_key = _cost_from_summary(summary, accumulator)
        if (summary.get("test_hard") is not None) or (out_root / "test_eval").exists():
            raise RuntimeError(
                "SkillOpt ran its own held-out evaluation despite "
                "evaluation.eval_test=false; optimization cost would be "
                "contaminated with deployment calls. Refusing to report it."
            )

        best_skill = out_root / "best_skill.md"
        initial_skill = out_root / "skills" / "skill_v0000.md"
        skill_text = best_skill.read_text(encoding="utf-8") if best_skill.exists() else skill_init.read_text(encoding="utf-8")
        accepted = (
            best_skill.exists()
            and initial_skill.exists()
            and best_skill.read_bytes() != initial_skill.read_bytes()
        )

        return OptimizationResult(
            final_skill_text=skill_text,
            cost=accumulator.snapshot(),
            wall_time_s=wall,
            skill_accepted=accepted,
            final_skill_path=str(best_skill) if best_skill.exists() else None,
            internal_gate={
                "mechanism": "SkillOpt selection-eval gate on the validation split",
                "best_step": summary.get("best_step"),
                "best_selection_hard": summary.get("best_selection_hard"),
                "baseline_selection_hard": summary.get("baseline_selection_hard"),
                "note": "this is SkillOpt's own internal gate, NOT the benchmark metric",
            },
            native_summary={
                "initial_skill": {
                    "condition": NATIVE_START_CONDITION["skillopt"],
                    "path": str(skill_init),
                    "chars": len(skill_init.read_text(encoding="utf-8")),
                    "bytes": len(skill_init.read_bytes()),
                    "sha256": hashlib.sha256(skill_init.read_bytes()).hexdigest(),
                    "source": "SkillOpt's own envs/<benchmark>/skills/initial.md",
                },
                "summary_json": str(summary_path) if summary_path.exists() else None,
                "split_dir": str(split_dir),
                "harness_contract_cfg_options": harness_contract,
                "token_summary": summary.get("token_summary"),
                "optimization_token_summary": summary.get("optimization_token_summary"),
                "optimization_cost_source_key": cost_source_key,
            },
        )
